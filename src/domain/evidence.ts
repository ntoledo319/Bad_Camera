/**
 * Evidence ZIP builder (public/sanitized by default) and verifier.
 *
 * Layout (spec §11):
 *   manifest.json
 *   records/observation.json      (public projection only — never DB rows)
 *   records/revisions.json        (revision chain metadata, public-safe fields)
 *   sources/sources.json
 *   media/approved-derivative-*.jpg
 *   report.pdf
 *   report.html                   (parallel accessible report; PDF is untagged)
 *   README.txt
 *   LICENSES.txt
 *   checksums.sha256              (manifest + payload, excluding itself)
 *
 * The manifest lists payload files but not itself. checksums.sha256 includes the exact
 * final manifest bytes and every payload file. The final ZIP hash is computed separately
 * and shown in the export receipt (it cannot be inside the ZIP).
 */
import { strToU8, strFromU8 } from 'fflate';
import type { Attachment, CameraInstallation, Claim, ExportManifest, Observation, Source, Transformation } from './schemas';
import { ExportManifest as ExportManifestSchema, SCHEMA_VERSION } from './schemas';
import { projectPublic, type DisclosureChoices, DEFAULT_DISCLOSURE, LIMITATIONS, DEMO_BANNER, type PublicProjection } from './projection';
import { renderPublicDerivative, hasSensitiveMetadata } from './image';
import { renderReportPdf, renderReportHtml, METHODOLOGY_TEXT } from './report';
import { readZipSafely, writeZipDeterministic, DEFAULT_ZIP_LIMITS, UnsafeArchiveError, type SafeZipLimits } from './safezip';
import { sha256Hex, canonicalJson, uuidv4 } from './hash';

export type DisclosureProfile = ExportManifest['selectedDisclosureProfile'];

export interface EvidencePhotoInput {
  attachment: Pick<Attachment, 'id' | 'sha256' | 'mime' | 'transformations' | 'redactionReviewedAt'>;
  /** Original bytes as stored privately. Only used to render a derivative unless profile is private-full-evidence. */
  originalBytes: Uint8Array;
}

export interface RevisionSummary {
  revision: number;
  revisionHash: string | null;
  previousRevisionHash: string | null;
  recordedAt: string;
  reason: string | null;
}

export interface EvidenceInput {
  observation: Observation;
  sources: Source[];
  claims: Claim[];
  installation: CameraInstallation | null;
  photos: EvidencePhotoInput[];
  revisions: RevisionSummary[];
  choices?: DisclosureChoices;
  profile?: DisclosureProfile;
  /** Must be explicitly true for private-full-evidence (after the in-app review screen). */
  privateFullConfirmed?: boolean;
  observerDistanceText?: string | null;
  createdAt?: string;
  exportId?: string;
}

export interface EvidenceResult {
  zip: Uint8Array;
  zipSha256: string;
  manifest: ExportManifest;
  projection: PublicProjection;
  files: Record<string, Uint8Array>;
}

